const run = promisify(execFile);
export const LOCAL_DATABASE = "wetscan_dev_guardg02";
/** Marker of the historical target on the previous machine: must never be reused by a new environment. */
export const HISTORICAL_MARKER = "wetscan-s01:f0927e49-0e70-4b90-913f-6cd6984df9d8";
/** Reviewed PostgreSQL 18 image (the same digest the repository's isolated fixtures use). */
export const PG_IMAGE =
  "docker.io/library/postgres@sha256:12060a1464f232e4f8c721538b342687c6f17cead32a389586cd683262b1d848";
export const CONTAINER = "wetscan-g02-local-pg";
export const VOLUME = "wetscan-g02-local-pg-data";
const RESERVED_PORTS = [5432, 55432]; // host PostgreSQL and the Sentinel development server
const markerPattern = /^wetscan-s01:[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/;

/** Strictly validated new target. Never the historical marker, never a reserved/Sentinel port, loopback only. */
export function localTarget(port: number, marker: string): Target {
  if (
    !Number.isInteger(port) ||
    port < 1024 ||
    port > 65535 ||
    RESERVED_PORTS.includes(port) ||
    !markerPattern.test(marker) ||
    marker === HISTORICAL_MARKER
  )
    throw Error("LOCAL_TARGET_INVALID");
  return { host: "127.0.0.1", port, database: LOCAL_DATABASE, marker };
}

export type LocalPurpose = "app" | "worker" | "migration";
const roleOf = { app: "wetscan_guard_app", worker: "wetscan_guard_worker", migration: "wetscan_guard_migrator" } as const;
/** Purpose-specific approval for exactly this target and migration plan. 1 hour to 30 days validity. */
export function localApproval(
  purpose: LocalPurpose,
  target: Target,
  planSha256: string,
  expiresAt: string,
  now = Date.now(),
) {
  const expires = Date.parse(expiresAt);
  if (!Number.isFinite(expires) || expires < now + 3600000 || expires > now + 30 * 86400000)
    throw Error("LOCAL_APPROVAL_EXPIRY_INVALID");
  localTarget(target.port, target.marker);
  if (!/^[a-f0-9]{64}$/.test(planSha256)) throw Error("LOCAL_APPROVAL_PLAN_INVALID");
  return {
    schemaVersion: 1 as const,
    status: "APPROVED" as const,
    module: "guard" as const,
    purpose,
    role: roleOf[purpose],
    target,
    actions: [purpose === "migration" ? "migrate_up" : "runtime"],
    approvedBy: "claude-code-generated-under-owner-development-instruction (not owner-signed)",
    approvedAt: new Date(now).toISOString(),
    expiresAt,
    migrationPlanSha256: planSha256,
    provenance: "new-isolated-local-environment",
  };
}

const win = process.platform === "win32";
const sys = () => {
  const s = process.env.SystemRoot;
  if (!s) throw Error("WINDOWS_METADATA_UNAVAILABLE");
  return s;
};
async function docker(args: string[]) {
  return (await run("docker", args, { windowsHide: true, maxBuffer: 1 << 24, timeout: 300000 })).stdout.trim();
}
async function dockerOrNull(args: string[]) {
  try {
    return await docker(args);
  } catch {
    return null;
  }
}
async function freePort(port: number) {
  await new Promise<void>((ok, no) => {
    const s = createServer();
    s.once("error", no);
    s.listen(port, "127.0.0.1", () => s.close(() => ok()));
  });
}
const parentDir = () => join(process.env.LOCALAPPDATA ?? join(process.env.HOME ?? ".", ".local/share"), "WetScanGuardG02");
const pointerFile = () => join(parentDir(), "current.json");

/** New empty directory, owner + SYSTEM only (same invariant the runtime verifies), created by this run. */
async function securePrivateRoot(root: string) {
  await mkdir(parentDir(), { recursive: true });
  await mkdir(root, { mode: 0o700 });
  if ((await readdir(root)).length) throw Error("NEW_EMPTY_ROOT_REQUIRED");
  if (win) {
    const o = { windowsHide: true, timeout: 20000, maxBuffer: 16384, encoding: "utf8" as const, env: { NODE_ENV: "production" as const, SystemRoot: sys(), WINDIR: sys() } };
    const sid = (await run(join(sys(), "System32/whoami.exe"), ["/user", "/fo", "csv", "/nh"], o)).stdout.match(/S-\d+(?:-\d+)+/)?.[0];
    if (!sid || sid === "S-1-5-18") throw Error("WINDOWS_IDENTITY_UNAVAILABLE");
    const icacls = join(sys(), "System32/icacls.exe");
    await run(icacls, [root, "/inheritance:r", "/grant:r", `*${sid}:(OI)(CI)F`, "*S-1-5-18:(OI)(CI)F"], o);
    await run(icacls, [root, "/setowner", `*${sid}`], o);
    await run(icacls, [root, "/remove:g", "*S-1-5-32-544"], o);
  }
  await assertPrivateRuntimeRoot(root);
}

interface Pointer {
  root: string;
  target: Target;
  port: number;
}
async function pointer(): Promise<Pointer> {
  return JSON.parse(await readFile(pointerFile(), "utf8"));
}
const read = async (root: string, name: string) => (await readFile(join(root, name), "utf8")).trim();

async function adminPool(p: Pointer) {
  return new pg.Pool({ host: p.target.host, port: p.port, database: p.target.database, user: "postgres", password: await read(p.root, "bootstrap.password"), max: 1, connectionTimeoutMillis: 2000 });
}
async function waitReady(pool: pg.Pool) {
  for (let n = 0; n < 60; n++) {
    try {
      await pool.query("SELECT 1");
      return;
    } catch {
      await new Promise((r) => setTimeout(r, 500));
    }
  }
  throw Error("DATABASE_NOT_READY");
}

export async function provision(port: number) {
  if (await dockerOrNull(["inspect", CONTAINER]) !== null) throw Error("LOCAL_ENVIRONMENT_ALREADY_EXISTS");
  await freePort(port);
  const target = localTarget(port, "wetscan-s01:" + randomUUID()),
    plan = await guardMigrationPlan(),
    id = randomUUID(),
    root = join(parentDir(), "wetscan-g02-runtime-db-" + id);
  await docker(["pull", "-q", PG_IMAGE]);
  await securePrivateRoot(root);
  const password = () => randomBytes(32).toString("hex");
  const pw = { bootstrap: password(), app: password(), worker: password(), migration: password() };
  const files: Record<string, string> = { "bootstrap.password": pw.bootstrap, "app.password": pw.app, "worker.password": pw.worker, "migration.password": pw.migration };
  for (const [name, value] of Object.entries(files)) await writeFile(join(root, name), value, { flag: "wx", mode: 0o600 });
  const expiresAt = new Date(Date.now() + 7 * 86400000).toISOString();
  for (const purpose of ["app", "worker", "migration"] as const)
    await writeFile(join(root, purpose + ".database.json"), JSON.stringify(localApproval(purpose, target, plan.sha256, expiresAt), null, 2) + "\n", { flag: "wx", mode: 0o600 });
  await docker(["volume", "create", "--label", "wetscan.env=g02-local", "--label", "wetscan.env.id=" + id, VOLUME]);
  await docker([
    "create", "--name", CONTAINER, "--label", "wetscan.env=g02-local", "--label", "wetscan.env.id=" + id,
    "--read-only", "--cap-drop", "ALL", "--user", "postgres",
    "--security-opt", "no-new-privileges", "--cpus", "2", "--memory", "1g", "--pids-limit", "256",
    "--tmpfs", "/tmp:rw,noexec,nosuid,size=64m", "--tmpfs", "/var/run/postgresql:rw,noexec,nosuid,size=8m",
    "--mount", `type=volume,source=${VOLUME},target=/var/lib/postgresql`,
    "--mount", `type=bind,source=${join(root, "bootstrap.password")},target=/run/bootstrap.password,readonly`,
    "--publish", `127.0.0.1:${port}:${port}`,
    "--env", "POSTGRES_PASSWORD_FILE=/run/bootstrap.password", "--env", "POSTGRES_DB=" + LOCAL_DATABASE, "--env", "PGPORT=" + port,
    "--env", "PGDATA=/var/lib/postgresql/18/docker", PG_IMAGE,
  ]);
  await docker(["start", CONTAINER]);
  await writeFile(pointerFile(), JSON.stringify({ root, target, port }), { flag: "wx" });
  const admin = await adminPool({ root, target, port });
  try {
    await waitReady(admin);
    const c = await admin.connect();
    try {
      // Empty-database and identity proof before any mutation.
      const empty = (await c.query("SELECT current_database() d, inet_server_port() p, (SELECT shobj_description(oid,'pg_database') FROM pg_database WHERE datname=current_database()) m, to_regnamespace('platform') pf, to_regnamespace('guard') g, to_regnamespace('sentinel') s, (SELECT count(*) FROM pg_roles WHERE rolname LIKE 'wetscan%')::int r")).rows[0];
      if (empty.d !== LOCAL_DATABASE || empty.p !== port || empty.m !== null || empty.pf || empty.g || empty.s || empty.r) throw Error("EMPTY_TARGET_REQUIRED");
      // The reviewed approval must verify against the real verifier before any migration.
      validateGuardApproval(JSON.parse(await read(root, "migration.database.json")), "migration", plan.sha256);
      await c.query("BEGIN");
      for (const role of ["wetscan_app", "wetscan_sentinel_worker", "wetscan_migrator"]) await c.query(`CREATE ROLE ${role} NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE`);
      for (const purpose of ["app", "worker", "migration"] as const)
        await c.query(`CREATE ROLE ${roleOf[purpose]} LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE PASSWORD '${pw[purpose]}'`);
      await c.query(`ALTER DATABASE ${LOCAL_DATABASE} OWNER TO wetscan_guard_migrator`);
      await c.query(`COMMENT ON DATABASE ${LOCAL_DATABASE} IS '${target.marker}'`);
      await c.query(`REVOKE ALL ON DATABASE ${LOCAL_DATABASE} FROM PUBLIC`);
      await c.query(`GRANT CONNECT ON DATABASE ${LOCAL_DATABASE} TO wetscan_guard_app,wetscan_guard_worker,wetscan_guard_migrator`);
      await c.query("SET LOCAL ROLE wetscan_guard_migrator");
      await c.query("CREATE SCHEMA platform; CREATE TABLE platform.schema_migrations(version text PRIMARY KEY,checksum char(64) NOT NULL,applied_at timestamptz NOT NULL DEFAULT clock_timestamp()); REVOKE ALL ON SCHEMA platform FROM PUBLIC");
      for (const m of (await migrationPlan(GUARD_PLATFORM_BASELINE)).migrations) {
        await c.query(m.up);
        await c.query("INSERT INTO platform.schema_migrations(version,checksum) VALUES($1,$2)", [m.version, m.checksum]);
      }
      await c.query(plan.migration.up);
      await c.query("INSERT INTO guard.schema_migrations(version,checksum) VALUES($1,$2)", [plan.migration.version, plan.migration.checksum]);
      await c.query("RESET ROLE");
      await c.query(plan.artifacts.find((a) => a.name === "platform-access.proposed.sql")!.sql);
      await c.query("COMMIT");
    } catch (e) {
      await c.query("ROLLBACK").catch(() => {});
      throw e;
    } finally {
      c.release();
    }
  } finally {
    await admin.end();
  }
  return { container: CONTAINER, volume: VOLUME, id, target, planSha256: plan.sha256, expiresAt };
}

/** Read-only metadata as the bootstrap operator, plus approval/target consistency. No data is returned beyond counts. */
export async function verify() {
  const p = await pointer(),
    plan = await guardMigrationPlan();
  await assertPrivateRuntimeRoot(p.root);
  for (const purpose of ["app", "worker", "migration"] as const) {
    const a = validateGuardApproval(JSON.parse(await read(p.root, purpose + ".database.json")), purpose, plan.sha256);
    parseApproval(a, p.target, purpose === "migration" ? "migrate_up" : "runtime", plan.sha256);
  }
  const admin = await adminPool(p),
    c = await admin.connect();
  try {
    await c.query("BEGIN READ ONLY");
    const r = (
      await c.query(`SELECT current_database() d, inet_server_port() p,
 (SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname=current_database()) owner,
 (SELECT shobj_description(oid,'pg_database') FROM pg_database WHERE datname=current_database()) marker,
 (SELECT jsonb_agg(version||':'||checksum ORDER BY version) FROM platform.schema_migrations) platform,
 (SELECT jsonb_agg(version||':'||checksum ORDER BY version) FROM guard.schema_migrations) guard,
 (SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE c.relrowsecurity AND c.relforcerowsecurity AND (n.nspname,c.relname) IN (('guard','scans'),('platform','jobs'),('platform','module_limits')))::int forced_rls,
 (SELECT count(*) FROM pg_roles WHERE rolname IN ('wetscan_guard_app','wetscan_guard_worker','wetscan_guard_migrator') AND NOT rolsuper AND NOT rolbypassrls AND NOT rolcreatedb AND NOT rolcreaterole)::int least_priv_roles,
 (SELECT count(*) FROM guard.scans)::int scans,(SELECT count(*) FROM platform.jobs WHERE module='guard')::int guard_jobs,
 (SELECT max_running FROM platform.module_limits WHERE module='guard') budget,
 has_table_privilege('wetscan_guard_app','guard.scans','INSERT') app_insert, has_table_privilege('wetscan_guard_worker','guard.scans','INSERT') worker_insert,
 has_database_privilege('wetscan_guard_app',current_database(),'CONNECT') app_connect, has_database_privilege('public',current_database(),'CONNECT') public_connect`)
    ).rows[0];
    await c.query("ROLLBACK");
    const expectedPlatform = (await migrationPlan(GUARD_PLATFORM_BASELINE)).migrations.map((m) => m.version + ":" + m.checksum);
    const ok =
      r.d === LOCAL_DATABASE && r.p === p.port && r.owner === "wetscan_guard_migrator" && r.marker === p.target.marker &&
      JSON.stringify(r.platform) === JSON.stringify(expectedPlatform) && r.guard?.length === 1 && r.forced_rls === 3 && r.least_priv_roles === 3 &&
      r.budget === 1 && r.app_insert === true && r.worker_insert === false && r.app_connect === true && r.public_connect === false;
    return { verified: ok, database: r.d, port: r.p, owner: r.owner, marker: r.marker, platformLedger: r.platform?.length, guardLedger: r.guard?.length, forcedRls: r.forced_rls, leastPrivilegeRoles: r.least_priv_roles, guardBudget: r.budget, scanRows: r.scans, guardJobRows: r.guard_jobs, publicConnect: r.public_connect, appCanInsertScans: r.app_insert, workerCanInsertScans: r.worker_insert, runtimeOperations: 0 };
  } finally {
    c.release();
    await admin.end();
  }
}

async function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  let out: unknown;
  if (cmd === "provision") {
    const i = rest.indexOf("--port");
    out = await provision(i >= 0 ? Number(rest[i + 1]) : 55434);
  } else if (cmd === "verify") out = await verify();
  else if (cmd === "start" || cmd === "stop") {
    await docker([cmd, CONTAINER]);
    out = { container: CONTAINER, action: cmd };
  } else if (cmd === "status") {
    out = JSON.parse((await docker(["inspect", "--format", "{{json .State}}", CONTAINER])) || "{}");
  } else if (cmd === "env") {
    // Process references only (paths are not secrets, but are not for chat): consumed with `eval "$(... env)"`.
    const p = await pointer();
    for (const [k, f] of [["APP_APPROVAL_FILE", "app.database.json"], ["APP_PASSWORD_FILE", "app.password"], ["WORKER_APPROVAL_FILE", "worker.database.json"], ["WORKER_PASSWORD_FILE", "worker.password"]])
      console.log(`export GUARD_DB_${k}='${resolve(p.root, f).replaceAll("\\", "/")}'`);
    // Target-only configuration (no repository policy, no scanner deployment): readiness checks only, scanning impossible.
    const config = join(p.root, "target-only.json");
    await writeFile(config, JSON.stringify({ version: 1, module: "guard-product-runtime", hosting: "self_hosted_node", target: p.target, policies: [], deployments: [], setup: "DATABASE_PREFLIGHT_ONLY_SCANNING_DISABLED" }, null, 2) + "\n", { flag: "wx", mode: 0o600 }).catch((e) => { if (e.code !== "EEXIST") throw e; });
    console.log(`export GUARD_PRODUCT_CONFIG_FILE='${config.replaceAll("\\", "/")}'`);
    return;
  } else throw Error("USAGE");
  console.log(JSON.stringify(out));
}
if (process.argv[1]?.replaceAll("\\", "/").endsWith("/guard-g02-local-env.ts"))
  main().catch((e) => {
    console.log(JSON.stringify({ error: e instanceof Error ? e.message.slice(0, 80) : "UNKNOWN" }));
    process.exitCode = 1;
  });

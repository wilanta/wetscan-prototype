/**
 * Fresh, isolated, owner-controlled Guard G02 development target on THIS machine (Docker PostgreSQL, loopback only).
 * Supersedes nothing: the historical target in guard-live-setup.ts and its approvals stay valid for their own database.
 *
 *   node --conditions=react-server --import tsx scripts/guard-g02-local-env.ts provision [--port 55434]
 *   node --conditions=react-server --import tsx scripts/guard-g02-local-env.ts verify|start|stop|status|env
 *
 * Passwords are generated here, written only to ACL-protected files, never printed, never in argv/env of children.
 * Approvals are generated by this tool under the owner's explicit development instruction (approvedBy says so); they are
 * not owner-signed, and use the repository's own approval schema/verifier.
 */
